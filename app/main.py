from fastapi import FastAPI
import subprocess
import shlex

app = FastAPI()

@app.get("/")
def home():
    return {"message": "Agentic Self-Healing Pipeline"}

@app.get("/ping")
def ping(host: str):
    # Secure implementation with argument splitting and quoting
    subprocess.call(shlex.split('ping ' + host))
    return {"status": "completed"}