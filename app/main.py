from fastapi import FastAPI
import subprocess
def sanitize_host(host):
    allowed_chars = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.-'
    return ''.join(filter(lambda x: x in allowed_chars, host))

app = FastAPI()

@app.get('/')
def home():
    return {'message': 'Agentic Self-Healing Pipeline'}

@app.get('/ping')
def ping(host: str):
    sanitized_host = sanitize_host(host)
    if subprocess.check_output(['ping', '-c', '1', sanitized_host], stderr=subprocess.STDOUT).decode('utf-8').startswith('PING'):
        return {'status': 'completed'}
    else:
        raise ValueError('Ping failed or invalid hostname')