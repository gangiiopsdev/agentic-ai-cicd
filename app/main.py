from fastapi import FastAPI
import subprocess

def safe_ping(host: str):
    # Sanitize the host parameter to prevent command injection
    allowed_chars = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.-_'
    if not all(char in allowed_chars for char in host):
        return {'status': 'failed', 'error': 'Invalid characters in host'}
    try:
        result = subprocess.run(['/usr/bin/ping', host], check=True, capture_output=True, text=True)
        return {'status': 'completed', 'output': result.stdout}
    except subprocess.CalledProcessError as e:
        return {'status': 'failed', 'error': str(e)}

app = FastAPI()

@app.get("/ping")
def ping(host: str):
    return safe_ping(host)