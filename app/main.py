from fastapi import FastAPI
import subprocess

app = FastAPI()

def escape_host(host):
    return host.replace(';', '').replace('&', '').replace('|', '')

@app.get("/ping")
def ping(host: str):
    escaped_host = escape_host(host)
    # Secure implementation
    subprocess.call(['ping', '-c', '4', escaped_host])
    return {"status": "completed"}